// x_source.rs — mawx WI-5: source schemes + registry raw-fetch
// (ψ/design/mawx-spec.md §2.2 resolution/fetch, §2.3 source schemes).
//
// The scheme set is a CLOSED, audited enum — not a plugin system for the
// resolver itself (spec §2.3: resolvers run before trust is established, so
// they must be audited core code; third parties bridge by laying out their
// repo like maw-plugins, never by injecting resolver code).
//
// Deterministic-core / IO-edge split:
// - PURE (unit-testable, no network/filesystem): `route_x_spec`,
//   `resolve_x_registry_verb`, `parse_x_registry`, `lookup_x_registry_verb`,
//   `x_registry_url`, `x_raw_file_url`, `x_manifest_fetch_info`,
//   `check_x_pin_chain`, `x_resolution_plan`.
// - IO EDGE (network via reqwest, filesystem via x_cache): `fetch_x_registry`,
//   `resolve_x_spec`, `execute_x_fetch`.
//
// Fetch discipline (spec §2.2 "the lean path"):
// - Registry bare verb → raw-fetch ONLY plugin.json + the pinned artifact at
//   the entry's commit. NO git clone on the happy path.
// - Every fetched artifact is sha256-verified against the full pin chain
//   (registry entry == manifest pin == explicit `--sha256`) BEFORE the bytes
//   are handed to `x_cache_put` (which re-verifies).
// - gh:/shorthand specs with a branch/tag ref that raw-fetch cannot pin →
//   shallow clone into a temp dir (same hygiene as `install_from_git`), then
//   the shared WI-1 `verify_package_dir` fork.
// - `file:`/local dirs never write to the cache (spec §2.3 local dev route).
// - NO auth headers, ever: public repos only (same posture as the http
//   host-fn precedent, which strips auth).

/// Default registry repo owner (spec §2.2: single default registry in V1).
pub const X_DEFAULT_REGISTRY_OWNER: &str = "Soul-Brews-Studio";

/// Default registry repo name.
pub const X_DEFAULT_REGISTRY_REPO: &str = "maw-plugins";

/// Raw-file host every GitHub fetch goes through.
pub const X_RAW_HOST: &str = "https://raw.githubusercontent.com";

/// Default network timeout for one raw-fetch request.
pub const X_FETCH_TIMEOUT_SECS: u64 = 30;

/// One entry of the registry's flat `verb → entry` map
/// (`registry.json`, generated by maw-plugins CI — spec WI-9).
#[derive(Debug, Clone, PartialEq, Eq, serde::Deserialize)]
pub struct XRegistryEntry {
    /// Commit SHA the package is pinned at (raw fetch at this commit is
    /// immutable end-to-end).
    pub commit: String,
    /// Artifact pin, `sha256:<64 lowercase hex>`.
    pub sha256: String,
    /// Package dir inside the registry repo (e.g. `packages/20-costs`).
    pub path: String,
    /// Package version at pin time.
    pub version: String,
    /// Capability grants (display/trust-card data; the manifest stays the
    /// enforcement source).
    #[serde(default)]
    pub capabilities: Vec<String>,
}

/// Registry-sourced resolution metadata carried into the fetch plan.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct XRegistryResolution {
    /// Verb the registry resolved.
    pub verb: String,
    /// Registry entry version.
    pub version: String,
    /// Registry entry capabilities.
    pub capabilities: Vec<String>,
    /// Registry entry pin (`sha256:<hex>`) — first link of the pin chain.
    pub sha256: String,
}

/// The files-to-fetch plan for one resolved source (spec §2.3: every scheme
/// funnels into the same verify gate; trust is scheme-independent).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum XFetchPlan {
    /// Raw-fetch `plugin.json` + the pinned artifact at an immutable commit —
    /// the primary, clone-free path.
    Raw {
        /// GitHub owner.
        owner: String,
        /// GitHub repo.
        repo: String,
        /// Commit SHA the files are fetched at.
        commit: String,
        /// Package dir inside the repo (empty = repo root).
        package_path: String,
        /// Registry metadata when the plan came from a registry verb.
        registry: Option<XRegistryResolution>,
    },
    /// Shallow `git clone` fallback for refs raw-fetch cannot pin
    /// (branch/tag) and for non-GitHub git URLs.
    Clone {
        /// Clone URL.
        url: String,
        /// Branch/tag passed to `git clone --branch`.
        reference: Option<String>,
        /// Package dir inside the clone.
        subpath: Option<String>,
    },
    /// Local dev dir (`file:`/`./`) — verified in place, never cached.
    Local {
        /// The path as given in the spec.
        path: String,
    },
}

/// A fully resolved fetch: canonical source string, the pinned commit when
/// one is known pre-fetch, and the files-to-fetch plan.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedFetch {
    /// Canonical source string (trust-store / lock form, spec §2.1).
    pub canonical_source: String,
    /// Pinned commit when the plan is already immutable (raw plans); `None`
    /// until the clone fallback resolves its ref.
    pub commit: Option<String>,
    /// What to fetch and how.
    pub plan: XFetchPlan,
}

/// First routing decision for a parsed spec: either the verb needs the
/// registry (network) to resolve, or the spec resolves purely.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum XRoute {
    /// Bare verb — resolve via `registry.json` (spec §2.2 step 3d).
    Registry {
        /// The verb to look up.
        verb: String,
        /// Optional `@ref` carried by the verb spec.
        reference: Option<XGitRef>,
    },
    /// Everything the spec pins directly, no registry needed.
    Resolved(ResolvedFetch),
}

/// The spec §2.1 `--dry-run` JSON plan:
/// `{source, commit, path, sha256, capabilities, sdk}`. Unknown-before-fetch
/// fields serialize as `null`.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct XResolutionPlan {
    /// Canonical source string.
    pub source: String,
    /// Pinned commit, when known.
    pub commit: Option<String>,
    /// Package dir inside the source repo, when known.
    pub path: Option<String>,
    /// Artifact pin (`sha256:<hex>`), when known.
    pub sha256: Option<String>,
    /// Capability grants, when known.
    pub capabilities: Option<Vec<String>>,
    /// Manifest `sdk` requirement — only known after the manifest is fetched.
    pub sdk: Option<String>,
}

/// IO-edge tuning for the fetch executor.
#[derive(Debug, Clone, Copy)]
pub struct XFetchOptions<'a> {
    /// CAS root (WI-6 `x_cache_root`).
    pub cache_root: &'a std::path::Path,
    /// Per-request network timeout in seconds.
    pub timeout_secs: u64,
    /// Unix seconds threaded into cache writes (no clock reads here).
    pub now: u64,
}

/// Outcome of one executed fetch: the enriched resolution plan, the
/// package-shaped dir the plugin runs from, and whether it lives in the CAS.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct XFetchedPackage {
    /// Resolution plan enriched with post-fetch facts (sha256, sdk, caps).
    pub resolution: XResolutionPlan,
    /// Package dir: the CAS entry dir, or the local dir for `file:` specs.
    pub package_dir: std::path::PathBuf,
    /// `false` only for the local dev route (spec: no cache write).
    pub cached: bool,
}

/// Everything the raw-fetch path needs from a fetched `plugin.json`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct XManifestFetchInfo {
    /// Manifest `name`.
    pub name: String,
    /// Dispatch verb: `cli.command`, falling back to `name` (spec §2.2:
    /// dispatch keys on `cli.command`, not the directory name).
    pub verb: String,
    /// Manifest `version`.
    pub version: String,
    /// `target == "wasm"` — the only raw-fetchable tier in V1.
    pub target_wasm: bool,
    /// Normalized `artifact.path` (leading `./` stripped), when present.
    pub artifact_path: Option<String>,
    /// Normalized `artifact.sha256` pin, when present.
    pub artifact_sha256: Option<String>,
    /// `bundledArtifacts[]` files to fetch alongside the artifact.
    pub bundled: Vec<XBundledArtifact>,
    /// Manifest `capabilities`.
    pub capabilities: Option<Vec<String>>,
    /// Manifest `sdk` requirement.
    pub sdk: Option<String>,
}

/// One `bundledArtifacts[]` entry the fetch plan must also pull.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct XBundledArtifact {
    /// Normalized package-relative path.
    pub path: String,
    /// Optional per-file pin; verified when present.
    pub sha256: Option<String>,
}

