    // ── executor: local route (offline) ────────────────────────────────

    #[test]
    fn local_route_verifies_in_place_and_never_caches() {
        let _guard = super::env_test_lock();
        let root = temp_root("local-route");
        let old = std::env::var_os("MAW_PLUGINS_LOCK");
        std::env::set_var("MAW_PLUGINS_LOCK", root.join("plugins.lock"));

        let package = root.join("pkg");
        std::fs::create_dir_all(&package).expect("package dir");
        std::fs::write(package.join("plugin.wasm"), b"\0asm\x01\x00\x00\x00x-source-local")
            .expect("wasm");
        let sha256 = maw_plugin_manifest::hash_file(&package.join("plugin.wasm")).expect("hash");
        std::fs::write(
            package.join("plugin.json"),
            format!(
                r#"{{"name":"x-source-local-demo","version":"1.0.0","target":"wasm","sdk":"^1.0.0","entry":{{"kind":"wasm","path":"plugin.wasm","export":"handle"}},"wasm":"./plugin.wasm","artifact":{{"path":"plugin.wasm","sha256":"{sha256}"}},"cli":{{"command":"x-source-local-demo"}}}}"#
            ),
        )
        .expect("manifest");

        let cache_root = root.join("cache");
        let options = XFetchOptions { cache_root: &cache_root, timeout_secs: 1, now: 1_000 };
        let spec = parse_x_spec(&format!("file:{}", package.display())).expect("parse");
        let fetch = match route_x_spec(&spec).expect("route") {
            XRoute::Resolved(resolved) => resolved,
            XRoute::Registry { .. } => panic!("file: must not hit the registry"),
        };
        let fetched = execute_x_fetch(&fetch, None, &options).expect("local execute");
        assert!(!fetched.cached, "local dev route never writes the cache");
        assert_eq!(fetched.package_dir, package);
        assert_eq!(fetched.resolution.sha256.as_deref(), Some(sha256.as_str()));
        assert_eq!(fetched.resolution.sdk.as_deref(), Some("^1.0.0"));
        assert!(!cache_root.exists(), "no cache write for local dirs");

        // A tampered local artifact refuses through the shared WI-1 fork.
        std::fs::write(package.join("plugin.wasm"), b"\0asm\x01\x00\x00\x00TAMPERED")
            .expect("tamper");
        let error = execute_x_fetch(&fetch, None, &options).expect_err("refused");
        assert!(error.contains("sha256 mismatch"), "{error}");

        match old {
            Some(value) => std::env::set_var("MAW_PLUGINS_LOCK", value),
            None => std::env::remove_var("MAW_PLUGINS_LOCK"),
        }
        let _ = std::fs::remove_dir_all(root);
    }

    // ── executor: clone fallback via a local git repo (offline) ────────

    #[test]
    fn clone_fallback_resolves_commit_verifies_and_caches() {
        let _guard = super::env_test_lock();
        let root = temp_root("clone-route");
        let old = std::env::var_os("MAW_PLUGINS_LOCK");
        std::env::set_var("MAW_PLUGINS_LOCK", root.join("plugins.lock"));

        // Build a real git repo holding one pinned wasm package.
        let repo = root.join("repo");
        let package = repo.join("packages").join("demo");
        std::fs::create_dir_all(&package).expect("package dir");
        let wasm: &[u8] = b"\0asm\x01\x00\x00\x00x-source-clone";
        std::fs::write(package.join("plugin.wasm"), wasm).expect("wasm");
        let sha256 = maw_plugin_manifest::hash_file(&package.join("plugin.wasm")).expect("hash");
        std::fs::write(
            package.join("plugin.json"),
            format!(
                r#"{{"name":"x-source-clone-demo","version":"1.2.0","target":"wasm","sdk":"^1.0.0","capabilities":["fs:read:cwd"],"entry":{{"kind":"wasm","path":"plugin.wasm","export":"handle"}},"wasm":"./plugin.wasm","artifact":{{"path":"plugin.wasm","sha256":"{sha256}"}},"cli":{{"command":"x-source-clone-demo"}}}}"#
            ),
        )
        .expect("manifest");
        for arguments in [
            vec!["init", "--initial-branch=main"],
            vec!["add", "."],
            vec![
                "-c",
                "user.email=x@test",
                "-c",
                "user.name=x-test",
                "commit",
                "-m",
                "package",
            ],
        ] {
            let output = std::process::Command::new("git")
                .arg("-C")
                .arg(&repo)
                .args(&arguments)
                .output()
                .expect("git");
            assert!(
                output.status.success(),
                "git {arguments:?}: {}",
                String::from_utf8_lossy(&output.stderr)
            );
        }

        let cache_root = root.join("cache");
        let options = XFetchOptions { cache_root: &cache_root, timeout_secs: 1, now: 2_000 };
        let fetch = ResolvedFetch {
            canonical_source: format!("file://{}", repo.display()),
            commit: None,
            plan: XFetchPlan::Clone {
                url: format!("file://{}", repo.display()),
                reference: Some("main".to_owned()),
                subpath: Some("packages/demo".to_owned()),
            },
        };
        let fetched = execute_x_fetch(&fetch, None, &options).expect("clone execute");
        assert!(fetched.cached);
        let commit = fetched.resolution.commit.as_deref().expect("resolved commit");
        assert_eq!(commit.len(), 40, "clone resolves a full commit SHA: {commit}");
        assert_eq!(fetched.resolution.sha256.as_deref(), Some(sha256.as_str()));
        assert_eq!(fetched.resolution.path.as_deref(), Some("packages/demo"));
        assert_eq!(
            fetched.resolution.capabilities.as_deref(),
            Some(&["fs:read:cwd".to_owned()][..])
        );
        // The CAS entry dir is package-shaped and holds the verified bytes.
        assert_eq!(
            std::fs::read(fetched.package_dir.join("plugin.wasm")).expect("artifact"),
            wasm
        );
        assert!(fetched.package_dir.join("plugin.json").is_file());
        let cached = super::x_cache_get(&cache_root, &sha256, 3_000).expect("cached");
        assert_eq!(cached.meta.verb, "x-source-clone-demo");
        assert_eq!(cached.meta.version, "1.2.0");

        // An explicit wrong --sha256 refuses through the shared fork.
        let wrong = x_sha256_of_bytes(b"other bytes").expect("hash");
        let error = execute_x_fetch(&fetch, Some(&wrong), &options).expect_err("pin refusal");
        assert!(error.contains("sha256"), "{error}");

        match old {
            Some(value) => std::env::set_var("MAW_PLUGINS_LOCK", value),
            None => std::env::remove_var("MAW_PLUGINS_LOCK"),
        }
        let _ = std::fs::remove_dir_all(root);
    }

